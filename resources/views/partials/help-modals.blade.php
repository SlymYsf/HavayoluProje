    <div data-help-id="pnr" data-help-title="PNR kodu nasıl bulunur?">
        <p>
            PNR, rezervasyonunuzu tanımlayan koddur ve <strong>DH-</strong> ön ekiyle
            başlayan beş karakterden oluşur. Örnek: <strong>DH-X4M1B</strong>
        </p>
        <p>Kodunuza şu yerlerden ulaşabilirsiniz:</p>
        <ul>
            <li>Rezervasyonu tamamladığınızda açılan onay sayfasında</li>
            <li>Rezervasyon onay e-postanızda</li>
            <li>Check-in hatırlatma e-postası ve SMS'inde</li>
            <li>Biniş kartınızın sağ alt köşesinde</li>
        </ul>
        <p>
            Kodu bulamıyorsanız rezervasyon sırasında verdiğiniz e-posta adresinin
            gelen kutusunu ve spam klasörünü kontrol edin.
        </p>
    </div>

    <div data-help-id="checkin-time" data-help-title="Check-in ne zaman açılır?">
        <p>
            Online check-in, uçuşunuzun kalkışına <strong>24 saat</strong> kala açılır
            ve kalkıştan <strong>20 dakika</strong> öncesine kadar açık kalır.
        </p>
        <p>
            Gidiş-dönüş biletlerinde her uçuş için ayrı check-in yapılır. Dönüş
            uçuşunuzun check-in'i, o uçuşun kalkışına 24 saat kala açılacaktır.
        </p>
        <p>
            Check-in penceresi açıldığında rezervasyon sırasında verdiğiniz e-posta
            adresine ve telefon numarasına bildirim gönderilir.
        </p>
        <p>
            Check-in'i tamamladığınızda biniş kartınız ekranda görüntülenir ve
            e-posta ile gönderilir. Havalimanına gelirken yanınızda bulundurun.
        </p>
    </div>

    <div data-help-id="cancel" data-help-title="Rezervasyonumu nasıl iptal ederim?">
        <p>
            <strong>Bilet yönetimi</strong> sekmesinden rezervasyon kodunuz ve
            soyadınızla giriş yaptıktan sonra sayfanın alt kısmındaki
            <strong>Rezervasyonu iptal et</strong> seçeneğini kullanabilirsiniz.
        </p>
        <p>
            İptal işlemi rezervasyondaki tüm yolcuları ve tüm uçuşları kapsar;
            tek bir yolcunun bileti ayrı olarak iptal edilemez.
        </p>
        <p>
            Kalkış saati geçmiş uçuşlar iptal edilemez. İade tutarı, ödemenin
            yapıldığı karta 3-5 iş günü içinde yansıtılır.
        </p>
        <p>
            Tarih veya uçuş değişikliği şu an desteklenmemektedir. Farklı bir tarihte
            seyahat etmek istiyorsanız mevcut rezervasyonunuzu iptal edip yeni bir
            rezervasyon oluşturmanız gerekir.
        </p>
    </div>

    <div data-help-id="bagaj" data-help-title="Bagaj hakkım ne kadar?">
        <p>
            Bagaj hakkınız kabin sınıfına göre değişir. Kabin bagajı için tüm
            sınıflarda <strong>8 kg</strong> ve 55x40x23 cm ölçü sınırı geçerlidir.
        </p>
        <ul>
            <li><strong>Economy:</strong> 20 kg kayıtlı bagaj</li>
            <li><strong>Premium Economy:</strong> 25 kg kayıtlı bagaj</li>
            <li><strong>Business:</strong> 30 kg kayıtlı bagaj</li>
        </ul>
        <p>
            Bagaj hakkı bilette yolcu başına tanımlıdır; aynı rezervasyondaki
            yolcuların hakları birleştirilemez.
        </p>
        <p>
            Hakkınızı aşan bagaj için havalimanında ek ücret ödemeniz gerekir.
            Ek bagajı önceden almak havalimanı tarifesine göre daha uygundur.
        </p>
    </div>

    <div data-help-id="evcil-hayvan" data-help-title="Evcil hayvanımla seyahat edebilir miyim?">
        <p>
            Kedi, köpek ve küçük kuşlar uçuşlarımızda kabul edilmektedir. Taşıma
            talebinizi <strong>uçuştan en az 48 saat önce</strong> bildirmeniz gerekir.
        </p>
        <p>
            Taşıma çantasıyla birlikte toplam ağırlığı <strong>8 kg</strong> altında
            olan hayvanlar kabinde, üzerindekiler kargo bölümünde taşınır. Kabinde
            taşınan hayvan uçuş boyunca çantasında kalmalıdır.
        </p>
        <p>
            Her uçuşta kabinde taşınabilecek hayvan sayısı sınırlıdır. Yurt dışı
            uçuşlarında varış ülkesinin sağlık belgesi ve aşı kartı şartları geçerlidir;
            bu belgelerin temini yolcunun sorumluluğundadır.
        </p>
        <p>
            Rehber köpekler bu sınırlamalara tabi değildir ve ücretsiz taşınır.
        </p>
    </div>

    <div data-help-id="odeme" data-help-title="Hangi ödeme yöntemlerini kullanabilirim?">
        <p>
